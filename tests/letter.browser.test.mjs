import assert from 'node:assert/strict';
import { before, after, test } from 'node:test';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { chromium, devices } from 'playwright';
import { createSiteServer } from '../scripts/server.mjs';
import { loadOrders } from '../scripts/order-api.mjs';

let server, browser, base, directory;
before(async () => {
  directory = await mkdtemp(join(tmpdir(), 'ytgb-browser-'));
  process.env.ORDER_DATA_FILE = join(directory, 'orders.json');
  process.env.ORDER_MEDIA_DIR = join(directory, 'media');
  process.env.ADMIN_EMAIL = 'owner@example.com';
  process.env.ADMIN_PASSWORD = 'browser-test-secret';
  process.env.ADMIN_SESSION_SECRET = 'browser-test-session-secret-long';
  await loadOrders();
  server = createSiteServer();
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  base = `http://127.0.0.1:${server.address().port}`;
  browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH || undefined });
});
after(async () => { await browser?.close(); if (server) await new Promise(resolve => server.close(resolve)); if (directory) await rm(directory, { recursive: true, force: true }); });

test('desktop order, admin confirmation and realtime recipient unlock', { timeout: 60000 }, async () => {
  const context = await browser.newContext({ viewport: { width: 1280, height: 900 } });
  const page = await context.newPage(); const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(base);
  assert.match(await page.title(), /Yêu thương gửi bạn/);
  assert.match(await page.locator('#header .brand').textContent(), /Yêu thương gửi bạn/);
  await page.locator('[data-create]').first().click();
  await page.locator('#message').fill('Một lá thư rất đặc biệt ❤️');
  const png = await page.evaluate(() => { const canvas = document.createElement('canvas'); canvas.width = 64; canvas.height = 32; const ctx = canvas.getContext('2d'); ctx.fillStyle = '#b36a70'; ctx.fillRect(0, 0, 64, 32); return canvas.toDataURL('image/png').split(',')[1]; });
  await page.locator('#photos-input').setInputFiles({ name: 'memory.png', mimeType: 'image/png', buffer: Buffer.from(png, 'base64') });
  await page.locator('.polaroid img').waitFor();
  await page.locator('#generate').click();
  await page.locator('#customer-phone').fill('0901234567');
  await page.locator('#customer-pin').fill('1234');
  await page.locator('#identity-form button[type=submit]').click();
  await page.waitForSelector('#share-dialog[open]');
  const id = (await page.locator('#order-code').textContent()).match(/YTGB[A-F0-9]{32}/)[0];
  const link = await page.locator('#share-url').inputValue();
  assert.match(link, /\/thu\/[A-Za-z0-9_-]{12}$/);
  assert.equal(await page.locator('#qr-code svg').count(), 1);
  const recipient = await context.newPage(); recipient.on('pageerror', error => errors.push(error.message));
  await recipient.goto(link);
  await recipient.getByText('Bức thư đang chờ xác nhận thanh toán').waitFor();
  const admin = await context.newPage(); admin.on('pageerror', error => errors.push(error.message));
  await admin.goto(base + '/admin');
  await admin.locator('#login-email').fill('owner@example.com');
  await admin.locator('#login-password').fill('browser-test-secret');
  await admin.locator('#login-btn').click();
  await admin.locator(`[data-order-id="${id}"] [data-action="preview"]`).click();
  assert.match(await admin.locator('#preview-modal-body').textContent(), /Một lá thư rất đặc biệt/);
  assert.equal(await admin.locator('#preview-modal-body img').count(), 1);
  await admin.locator('#preview-modal [data-close]').click();
  await admin.locator(`[data-order-id="${id}"] [data-action="pay"]`).click();
  await admin.locator('#confirm-ok').click();
  await recipient.locator('.seal-button').waitFor();
  await page.waitForFunction(() => document.querySelector('#order-state').textContent.includes('Đã mở khóa Premium'));
  await recipient.locator('.seal-button').click({ force: true });
  await recipient.locator('.reading-paper').waitFor();
  await recipient.locator('.skip-typing').click();
  assert.equal(await recipient.locator('.letter-content').textContent().then(t => t.trim()), 'Một lá thư rất đặc biệt ❤️');
  assert.equal(await recipient.locator('.memory-photo').count(), 1);
  await recipient.locator('#create-similar').click();
  assert.equal(new URL(recipient.url()).pathname, '/');
  assert.equal(new URL(recipient.url()).hash, '#studio');
  assert.deepEqual(errors, []);
  await context.close();
});

