test('shop owner can filter, reset edits and revoke a live letter on mobile', { timeout: 60000 }, async () => {
  const context = await browser.newContext(devices['iPhone 13']);
  const admin = await context.newPage();
  await admin.goto(base + '/admin');
  await admin.locator('#login-email').fill('owner@example.com');
  await admin.locator('#login-password').fill('browser-test-secret');
  await admin.locator('#login-btn').click();
  await admin.locator('.filter-tab[data-filter="paid"]').click();
  await admin.locator('#search-input').fill('0901234567');
  const row = admin.locator('#orders-body tr').filter({ hasText: '0901234567' }).first(); await row.waitFor();
  const link = await row.locator('.link-cell a').getAttribute('href');
  const recipient = await context.newPage(); await recipient.goto(base + link); await recipient.locator('.seal-button').waitFor();
  await row.locator('[data-action="reset-edits"]').click();
  await admin.locator('#confirm-ok').click();
  await admin.waitForFunction(() => document.querySelector('#admin-toast').textContent.includes('Đã cấp lại 3 lượt'));
  assert.match(await row.locator('.edit-count').textContent(), /3\/3/);
  await row.locator('[data-action="revoke"]').click(); await admin.locator('#confirm-ok').click();
  await recipient.getByText('Bức thư đã bị thu hồi.', { exact: true }).waitFor();
  await admin.locator('.filter-tab[data-filter="revoked"]').click();
  await admin.locator('[data-action="restore"]').first().click(); await admin.locator('#confirm-ok').click();
  await recipient.locator('.seal-button').waitFor();
  await admin.locator('#logout-btn').click(); await admin.locator('#login-screen').waitFor();
  assert.equal(await admin.locator('#orders-body tr').count(), 0);
  await context.close();
});
