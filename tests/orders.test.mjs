import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createSiteServer } from '../scripts/server.mjs';
import { loadOrders } from '../scripts/order-api.mjs';

test('order payment, recovery and admin authorization', async () => {
  const directory = await mkdtemp(join(tmpdir(), 'ytgb-orders-'));
  process.env.ORDER_DATA_FILE = join(directory, 'orders.json');
  process.env.ADMIN_EMAIL = 'owner@example.com';
  process.env.ADMIN_PASSWORD = 'correct-secret';
  process.env.ADMIN_SESSION_SECRET = 'test-session-secret';
  await loadOrders();
  const server = createSiteServer();
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const base = `http://127.0.0.1:${server.address().port}`;
  const send = async (path, method = 'GET', value, cookie) => fetch(base + path, { method, headers: { 'Content-Type': 'application/json', ...(cookie ? { Cookie: cookie } : {}) }, body: value ? JSON.stringify(value) : undefined });
  const letterData = { title: 'Một lá thư', recipient: 'Bạn', message: 'Yêu thương', sender: 'Tớ', photo: '', audio: '' };
  try {
    const createdResponse = await send('/api/orders', 'POST', { phone: '0901234567', pin: '1234', letterData });
    assert.equal(createdResponse.status, 201);
    const created = await createdResponse.json();
    assert.match(created.id, /^YTGB[A-F0-9]{32}$/);
    assert.match(created.letterUrl, /^\/thu\/[A-Za-z0-9_-]{12}$/);
    assert.equal((await send(created.letterUrl)).status, 200);
    assert.equal((await send('/api/orders/recover', 'POST', { id: created.id })).status, 400);
    assert.equal((await send('/api/orders/recover', 'POST', { id: created.id, pin: '9999' })).status, 404);
    assert.equal((await (await send(`/api/orders/${created.id}`)).json()).letterData, undefined);
    assert.equal((await send(`/api/admin/orders/${created.id}/status`, 'PATCH', { status: 'paid' })).status, 401);
    const login = await send('/api/admin/login', 'POST', { email: 'owner@example.com', password: 'correct-secret' });
    assert.equal(login.status, 200);
    const cookie = login.headers.get('set-cookie').split(';')[0];
    assert.equal((await send(`/api/admin/orders/${created.id}/status`, 'PATCH', { status: 'paid' }, cookie)).status, 200);
    const paid = await (await send(`/api/orders/${created.id}`)).json();
    assert.equal(paid.letterData.message, 'Yêu thương');
    const recovered = await (await send('/api/orders/recover', 'POST', { phone: '0901234567', pin: '1234' })).json();
    assert.equal(recovered[0].id, created.id);
    assert.equal((await send(`/api/orders/${created.id}`, 'PUT', { ownerToken: 'wrong', letterData })).status, 403);
    assert.equal((await send(`/api/orders/${created.id}`, 'PUT', { ownerToken: recovered[0].ownerToken, letterData: { ...letterData, message: 'Đã sửa' } })).status, 200);
    const token = recovered[0].ownerToken;
    assert.equal((await send(`/api/orders/${created.id}`, 'PUT', { ownerToken: token, letterData: { ...letterData, message: 'Sửa 2' } })).status, 200);
    assert.equal((await send(`/api/orders/${created.id}`, 'PUT', { ownerToken: token, letterData: { ...letterData, message: 'Sửa 3' } })).status, 200);
    assert.equal((await send(`/api/orders/${created.id}`, 'PUT', { ownerToken: token, letterData: { ...letterData, message: 'Sửa 4' } })).status, 409);
    assert.equal((await send(`/api/admin/orders/${created.id}/reset-edits`, 'POST')).status, 401);
    const reset = await send(`/api/admin/orders/${created.id}/reset-edits`, 'POST', undefined, cookie);
    assert.equal(reset.status, 200);
    assert.equal((await reset.json()).editsRemaining, 3);
    assert.equal((await send(`/api/orders/${created.id}`, 'PUT', { ownerToken: token, letterData: { ...letterData, message: 'Sửa sau hỗ trợ' } })).status, 200);
    assert.equal((await send(`/api/orders/${created.id}/settings`, 'PATCH', { ownerToken: token, password: 'private-pass' })).status, 200);
    assert.equal((await (await send(`/api/orders/${created.id}`)).json()).letterData, undefined);
    const slug = created.letterUrl.split('/').pop();
    assert.equal((await send(`/api/thu/${slug}/open`, 'POST', { password: 'wrong' })).status, 403);
    assert.equal((await send(`/api/thu/${slug}/open`, 'POST', { password: 'private-pass' })).status, 200);
    assert.equal((await send(`/api/orders/${created.id}/settings`, 'PATCH', { ownerToken: token, linkRevoked: true })).status, 200);
    assert.equal((await send(`/api/thu/${slug}/open`, 'POST', { password: 'private-pass' })).status, 404);
    assert.equal((await send(`/api/admin/orders/${created.id}/status`, 'PATCH', { status: 'revoked' }, cookie)).status, 200);
    assert.equal((await (await send(`/api/orders/${created.id}`)).json()).letterData, undefined);
    const catalog = await (await send('/api/catalog')).json();
    assert.equal(catalog.giftSets.length, 3);
    const shipping = { recipientName: 'Nguyễn An', recipientPhone: '0912345678', address: '12 Đường Hoa, Phường 1, Quận 3, TP Hồ Chí Minh', deliveryDate: new Date(Date.now() + 86400000 * 2).toISOString().slice(0, 10), timeNote: 'Sau 17 giờ', cardNote: 'Chúc mừng sinh nhật', buyerPhone: '0987654321' };
    assert.equal((await send('/api/orders', 'POST', { phone: '0987654321', pin: '4321', package: 'gift', giftSetId: 'flowers', letterData })).status, 400);
    const giftResponse = await send('/api/orders', 'POST', { phone: '0987654321', pin: '4321', package: 'gift', giftSetId: 'flowers', shipping, letterData, quote: { total: 1 } });
    assert.equal(giftResponse.status, 201);
    const gift = await giftResponse.json();
    assert.equal(gift.quote.total, catalog.letterPrice + catalog.giftSets[0].price + catalog.estimatedShipping);
    assert.equal(gift.shippingStatus, 'preparing');
    const publicGift = await (await send(`/api/orders/${gift.id}`)).json();
    assert.equal(publicGift.shipping, undefined);
    assert.equal(publicGift.quote, undefined);
    assert.equal((await send(`/api/admin/orders/${gift.id}/shipping`, 'PATCH', { status: 'sent' }, cookie)).status, 409);
    assert.equal((await send(`/api/admin/orders/${gift.id}/status`, 'PATCH', { status: 'paid' }, cookie)).status, 200);
    assert.equal((await send(`/api/admin/orders/${gift.id}/shipping`, 'PATCH', { status: 'sent' })).status, 401);
    assert.equal((await send(`/api/admin/orders/${gift.id}/shipping`, 'PATCH', { status: 'sent' }, cookie)).status, 200);
    assert.equal((await send(`/api/admin/orders/${gift.id}/shipping`, 'PATCH', { status: 'delivered' }, cookie)).status, 200);
    assert.equal((await (await send(`/api/orders/recover`, 'POST', { id: gift.id, pin: '4321' })).json()).shipping.address, shipping.address);
    assert.equal((await send('/api/admin/logout', 'POST', undefined, cookie)).status, 200);
    assert.equal((await send('/api/admin/orders', 'GET', undefined, cookie)).status, 401);
    assert.equal((await send(`/api/admin/orders/${created.id}/reset-edits`, 'POST', undefined, cookie)).status, 401);
  } finally { await new Promise(resolve => server.close(resolve)); await rm(directory, { recursive: true, force: true }); }
});
